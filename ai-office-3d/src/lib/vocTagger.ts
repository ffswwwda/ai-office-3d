/** 对单条评论做 9 维规则打标 */
export function tagComment(text: string): VocTagResult {
  const t = text || ''
  const dims: VocDim[] = []
  let pos = 0
  let neg = 0
  for (const dimName of VOC_DIMENSION_NAMES) {
    const rules = DICT[dimName]
    const tags: string[] = []
    for (const r of rules) {
      if (r.kw.test(t)) {
        tags.push(r.tag)
        if (dimName === '满意度') {
          if (r.tag === '正面') pos++
          if (r.tag === '负面') neg++
        }
      }
    }
    if (tags.length > 0) dims.push({ dim: dimName, tags: Array.from(new Set(tags)) })
  }
  const sentiment: VocTagResult['sentiment'] = pos > neg ? '正面' : neg > pos ? '负面' : '中性'
  return { dims, sentiment }
}
