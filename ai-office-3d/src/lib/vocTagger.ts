/** VOC 9 维规则打标引擎（离线、确定、可演示）
 *  用于员工「小灵」的工作台：用户贴评论 → 逐条实时打标 → 可见表格变化。
 *  规则版保证无密钥也能跑通；接入 LLM 时可在调用处替换为真实语义打标。
 */

export interface VocDim {
  dim: string
  tags: string[]
}
export interface VocTagResult {
  dims: VocDim[]
  sentiment: '正面' | '中性' | '负面'
}

/** 维度名顺序（也用于表格列） */
